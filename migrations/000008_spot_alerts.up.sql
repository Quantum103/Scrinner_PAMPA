-- Explicit Telegram subscriptions and durable delivery queue for Spot momentum alerts.
CREATE TABLE spot_alert_subscriptions (
    user_id BIGINT PRIMARY KEY REFERENCES telegram_users(id) ON DELETE CASCADE,
    subscribed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE spot_momentum_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL,
    reference_at TIMESTAMPTZ NOT NULL,
    current_price NUMERIC(30, 12) NOT NULL CHECK (current_price > 0),
    reference_price NUMERIC(30, 12) NOT NULL CHECK (reference_price > 0),
    change_percent NUMERIC(16, 8) NOT NULL CHECK (change_percent > 0),
    window_seconds INTEGER NOT NULL CHECK (window_seconds BETWEEN 1 AND 86400),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT spot_momentum_alert_time_chk CHECK (detected_at > reference_at),
    CONSTRAINT spot_momentum_alert_unique_event UNIQUE (symbol, detected_at, reference_at)
);

CREATE INDEX spot_momentum_alerts_detected_idx
    ON spot_momentum_alerts (detected_at DESC, id DESC);

CREATE TABLE spot_alert_deliveries (
    user_id BIGINT NOT NULL REFERENCES telegram_users(id) ON DELETE CASCADE,
    alert_id BIGINT NOT NULL REFERENCES spot_momentum_alerts(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'cancelled')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    lease_until TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, alert_id),
    CONSTRAINT spot_alert_delivery_sent_chk CHECK (
        (status = 'sent' AND sent_at IS NOT NULL) OR status <> 'sent'
    )
);

CREATE INDEX spot_alert_deliveries_pending_idx
    ON spot_alert_deliveries (next_attempt_at, created_at)
    WHERE status IN ('pending', 'failed');

CREATE INDEX spot_alert_deliveries_stale_lease_idx
    ON spot_alert_deliveries (lease_until)
    WHERE status = 'sending';
