-- Multiple independent, user-configurable Spot momentum rules.
ALTER TABLE spot_momentum_alerts
    ADD COLUMN threshold_percent NUMERIC(10, 4) NOT NULL DEFAULT 5.0000
        CHECK (threshold_percent BETWEEN 0.01 AND 1000);

ALTER TABLE spot_momentum_alerts
    DROP CONSTRAINT spot_momentum_alert_unique_event;

ALTER TABLE spot_momentum_alerts
    ADD CONSTRAINT spot_momentum_alert_unique_event
    UNIQUE (symbol, detected_at, reference_at, window_seconds, threshold_percent);

CREATE TABLE spot_alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES telegram_users(id) ON DELETE CASCADE,
    threshold_percent NUMERIC(10, 4) NOT NULL
        CHECK (threshold_percent BETWEEN 0.01 AND 1000),
    window_seconds INTEGER NOT NULL
        CHECK (window_seconds BETWEEN 60 AND 3600 AND window_seconds % 60 = 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT spot_alert_rule_unique UNIQUE (user_id, threshold_percent, window_seconds)
);

CREATE INDEX spot_alert_rules_lookup_idx
    ON spot_alert_rules (window_seconds, threshold_percent, user_id);

-- Preserve existing behaviour for every user who was already subscribed.
INSERT INTO spot_alert_rules (user_id, threshold_percent, window_seconds)
SELECT user_id, 5.0000, 900
FROM spot_alert_subscriptions
ON CONFLICT (user_id, threshold_percent, window_seconds) DO NOTHING;
