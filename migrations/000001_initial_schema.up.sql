-- Пользователи Telegram и их индивидуальные настройки.
CREATE TABLE telegram_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL UNIQUE CHECK (telegram_id > 0),
    username TEXT NOT NULL DEFAULT '',
    first_name TEXT NOT NULL DEFAULT '',
    last_name TEXT NOT NULL DEFAULT '',
    language_code TEXT NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_settings (
    user_id BIGINT PRIMARY KEY REFERENCES telegram_users(id) ON DELETE CASCADE,
    rsi_length INTEGER NOT NULL DEFAULT 14 CHECK (rsi_length BETWEEN 2 AND 500),
    ema_length INTEGER NOT NULL DEFAULT 9 CHECK (ema_length BETWEEN 1 AND 500),
    instrument_limit INTEGER NOT NULL DEFAULT 100 CHECK (instrument_limit BETWEEN 1 AND 10000),
    scan_all_instruments BOOLEAN NOT NULL DEFAULT FALSE,
    notify_long BOOLEAN NOT NULL DEFAULT TRUE,
    notify_short BOOLEAN NOT NULL DEFAULT TRUE,
    notify_confluence BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- В таблице присутствуют только включённые таймфреймы.
CREATE TABLE user_timeframes (
    user_id BIGINT NOT NULL REFERENCES telegram_users(id) ON DELETE CASCADE,
    timeframe TEXT NOT NULL CHECK (timeframe IN ('5', '15', '60')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, timeframe)
);

-- Каталог поддерживаемых Bybit USDT Linear Perpetual.
-- Инструменты не удаляются физически: это сохраняет ссылки из истории сигналов.
CREATE TABLE instruments (
    symbol TEXT PRIMARY KEY,
    base_coin TEXT NOT NULL,
    quote_coin TEXT NOT NULL,
    settle_coin TEXT NOT NULL,
    contract_type TEXT NOT NULL,
    status TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    turnover_24h NUMERIC(30, 8) NOT NULL DEFAULT 0 CHECK (turnover_24h >= 0),
    last_price NUMERIC(30, 12),
    instrument_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ticker_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (quote_coin = 'USDT'),
    CHECK (settle_coin = 'USDT'),
    CHECK (contract_type = 'LinearPerpetual')
);

CREATE INDEX instruments_active_turnover_idx
    ON instruments (turnover_24h DESC, symbol)
    WHERE is_active = TRUE;

-- Индивидуальные ручные включения/исключения пользователя.
CREATE TABLE user_instrument_preferences (
    user_id BIGINT NOT NULL REFERENCES telegram_users(id) ON DELETE CASCADE,
    symbol TEXT NOT NULL REFERENCES instruments(symbol) ON DELETE RESTRICT,
    preference TEXT NOT NULL CHECK (preference IN ('include', 'exclude')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, symbol)
);

CREATE INDEX user_instrument_preferences_symbol_idx
    ON user_instrument_preferences (symbol, preference);

-- Сигнал — глобальное рыночное событие, не дублируемое для разных пользователей.
CREATE TABLE signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL REFERENCES instruments(symbol) ON DELETE RESTRICT,
    timeframe TEXT NOT NULL CHECK (timeframe IN ('5', '15', '60')),
    direction TEXT NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    candle_start TIMESTAMPTZ NOT NULL,
    candle_close TIMESTAMPTZ NOT NULL,
    close_price NUMERIC(30, 12) NOT NULL CHECK (close_price > 0),
    rsi NUMERIC(12, 8) NOT NULL CHECK (rsi >= 0 AND rsi <= 100),
    ema_rsi NUMERIC(12, 8) NOT NULL CHECK (ema_rsi >= 0 AND ema_rsi <= 100),
    detected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT signals_candle_range_chk CHECK (candle_close > candle_start),
    CONSTRAINT signals_unique_market_event UNIQUE (symbol, timeframe, candle_start, direction)
);

CREATE INDEX signals_detected_at_idx ON signals (detected_at DESC, id DESC);
CREATE INDEX signals_symbol_detected_idx ON signals (symbol, detected_at DESC);
CREATE INDEX signals_direction_detected_idx ON signals (direction, detected_at DESC);
CREATE INDEX signals_timeframe_detected_idx ON signals (timeframe, detected_at DESC);

-- Состояние обработки каждой независимой пары инструмент/таймфрейм.
CREATE TABLE scanner_states (
    symbol TEXT NOT NULL REFERENCES instruments(symbol) ON DELETE RESTRICT,
    timeframe TEXT NOT NULL CHECK (timeframe IN ('5', '15', '60')),
    last_processed_candle_start TIMESTAMPTZ NOT NULL,
    last_close NUMERIC(30, 12) NOT NULL DEFAULT 0,
    last_rsi NUMERIC(12, 8),
    last_ema_rsi NUMERIC(12, 8),
    last_cross_direction TEXT CHECK (last_cross_direction IS NULL OR last_cross_direction IN ('LONG', 'SHORT')),
    last_cross_at TIMESTAMPTZ,
    initialized BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (symbol, timeframe)
);

CREATE INDEX scanner_states_updated_idx ON scanner_states (updated_at DESC);

-- Очередь доставки сигнала каждому конкретному пользователю.
CREATE TABLE signal_deliveries (
    user_id BIGINT NOT NULL REFERENCES telegram_users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES signals(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    lease_until TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, signal_id),
    CONSTRAINT signal_delivery_sent_chk CHECK (
        (status = 'sent' AND sent_at IS NOT NULL) OR status <> 'sent'
    )
);

CREATE INDEX signal_deliveries_pending_idx
    ON signal_deliveries (next_attempt_at, created_at)
    WHERE status IN ('pending', 'failed');

CREATE INDEX signal_deliveries_stale_lease_idx
    ON signal_deliveries (lease_until)
    WHERE status = 'sending';

CREATE INDEX signal_deliveries_user_history_idx
    ON signal_deliveries (user_id, created_at DESC);
